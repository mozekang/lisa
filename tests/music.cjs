const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3000');
 await page.locator('#settings').click();
 assert.equal(await page.locator('#bgm-enabled').isChecked(),false);
 await page.locator('#bgm-enabled').check();
 await page.waitForFunction(()=>{const p=document.getElementById('bgm');return !p.paused&&p.currentTime>0&&p.duration>0});
 assert.equal(await page.locator('#bgm').evaluate(p=>p.loop),true);
 assert.equal(await page.locator('#bgm').evaluate(p=>p.volume),.35);
 console.log('PASS BGM1 decoded and playback clock advancing, loop enabled');
 await page.locator('#bgm-volume').focus();await page.keyboard.press('Home');
 assert.equal(await page.locator('#bgm').evaluate(p=>p.volume),0);
 await page.keyboard.press('End');assert.equal(await page.locator('#bgm').evaluate(p=>p.volume),1);
 await page.keyboard.press('ArrowLeft');assert.equal(await page.locator('#bgm').evaluate(p=>p.volume),.99);
 await page.locator('#bgm-track').selectOption('BGM2');
 await page.waitForFunction(()=>{const p=document.getElementById('bgm');return p.currentSrc.endsWith('BGM2.mp3')&&!p.paused&&p.currentTime>0&&p.duration>0});
 console.log('PASS volume 0–100 and BGM2 decoded and playing after switch');
 await page.locator('#language-zh').click();assert.equal(await page.locator('#music-heading').textContent(),'背景音乐');
 assert.equal(await page.locator('#bgm-status').textContent(),'播放中');
 await page.reload();await page.locator('#settings').click();
 await page.waitForFunction(()=>!document.getElementById('bgm').paused);
 assert.equal(await page.locator('#bgm-track').inputValue(),'BGM2');assert.equal(await page.locator('#bgm-volume').inputValue(),'99');assert(await page.locator('#bgm-enabled').isChecked());
 const bounds=await page.locator('#settings-dialog').boundingBox();assert(bounds.y>=0&&bounds.y+bounds.height<=720);
 await page.locator('#close-settings').click();await page.locator('#sound').click();
 assert(await page.locator('#bgm').evaluate(p=>p.paused));
 await page.locator('#settings').click();assert.equal(await page.locator('#bgm-enabled').isChecked(),false);
 await page.locator('#bgm-track').selectOption('BGM1');assert(await page.locator('#bgm').evaluate(p=>p.paused));
 await page.reload();await page.locator('#settings').click();assert.equal(await page.locator('#bgm-enabled').isChecked(),false);assert(await page.locator('#bgm').evaluate(p=>p.paused));
 console.log('PASS saved preferences, translated settings, toolbar pause, switching while paused, desktop dialog fits');
 assert.deepEqual(errors,[]);await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
